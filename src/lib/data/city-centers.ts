export function normalizeTurkishForMatch(value: string): string {
  return value.trim().toLocaleLowerCase("tr");
}

function matchCityKey(raw: string): string | null {
  const trimmed = raw.trim();
  if (!trimmed) return null;

  const normalized = normalizeTurkishForMatch(trimmed);

  for (const city of Object.keys(CITY_CENTERS)) {
    if (normalizeTurkishForMatch(city) === normalized) return city;
  }

  for (const city of Object.keys(CITY_CENTERS)) {
    const cityNorm = normalizeTurkishForMatch(city);
    if (cityNorm.includes(normalized) || normalized.includes(cityNorm)) {
      return city;
    }
  }

  return null;
}

function matchDistrictKey(cityKey: string, raw: string): string | null {
  const trimmed = raw.trim();
  if (!trimmed) return null;

  const districts = DISTRICT_CENTERS[cityKey];
  if (!districts || Object.keys(districts).length === 0) return null;

  const normalized = normalizeTurkishForMatch(trimmed);

  for (const district of Object.keys(districts)) {
    if (normalizeTurkishForMatch(district) === normalized) return district;
  }

  for (const district of Object.keys(districts)) {
    const districtNorm = normalizeTurkishForMatch(district);
    if (districtNorm.includes(normalized) || normalized.includes(districtNorm)) {
      return district;
    }
  }

  return null;
}

/** district verilmişse önce ilçe merkezine, yoksa il merkezine bakar. */
export function resolveCityCenter(
  city: string,
  district?: string | null,
): GeoPoint2 | null {
  const cityKey = matchCityKey(city);
  if (!cityKey) return null;

  if (district && district.trim()) {
    const districtKey = matchDistrictKey(cityKey, district);
    if (districtKey) {
      const districtPoint = DISTRICT_CENTERS[cityKey]?.[districtKey];
      if (districtPoint) return districtPoint;
    }
  }

  return CITY_CENTERS[cityKey] ?? null;
}
